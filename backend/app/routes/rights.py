"""Rights and legal aid routes.

Returns curated data from /data files — never generated ad hoc by the model.
"""

import json
import logging
from pathlib import Path

from fastapi import APIRouter, Query, Request, Response
from slowapi import Limiter
from slowapi.util import get_remote_address

from app.config import settings
from app.models.schemas import DocumentType, LegalAidInfo, RightsResponse

logger = logging.getLogger(__name__)
router = APIRouter(tags=["rights"])
limiter = Limiter(key_func=get_remote_address)

# Cache loaded data
_rights_cache: dict[str, dict] = {}
_legal_aid_cache: dict[str, dict] = {}


def _load_json_data(file_path: Path) -> dict | list:
    """Load and cache JSON data from file."""
    try:
        return json.loads(file_path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        logger.warning("Data file not found: %s", file_path)
        return {}
    except json.JSONDecodeError as e:
        logger.error("Invalid JSON in %s: %s", file_path, e)
        return {}


def _get_rights_data(doc_type: str) -> dict:
    """Get rights checklist data for a document type."""
    if doc_type not in _rights_cache:
        file_path = settings.data_dir / "statutes" / f"{doc_type}_rights.json"
        data = _load_json_data(file_path)
        _rights_cache[doc_type] = data if isinstance(data, dict) else {}
    return _rights_cache[doc_type]


def _get_legal_aid_data() -> dict:
    """Get legal aid contact and eligibility data."""
    if "main" not in _legal_aid_cache:
        file_path = settings.data_dir / "legal_aid" / "legal_aid.json"
        data = _load_json_data(file_path)
        _legal_aid_cache["main"] = data if isinstance(data, dict) else {}
    return _legal_aid_cache["main"]


@router.get("/rights", response_model=RightsResponse)
@limiter.limit("20/minute")
async def get_rights(
    request: Request,
    response: Response,
    doc_type: DocumentType = Query(..., description="Document/situation type"),
    state: str = Query(..., min_length=2, max_length=100, description="Indian state name"),
) -> RightsResponse:
    """Get rights checklist and legal aid information.

    Data is sourced from curated files in /data — not generated by the AI model.
    Contact details should be verified with respective authorities before relying on them.
    """
    response.headers["Cache-Control"] = "public, max-age=3600, stale-while-revalidate=86400"
    rights_data = _get_rights_data(doc_type.value)
    legal_aid_data = _get_legal_aid_data()

    # Get rights for this document type
    rights_list = rights_data.get("rights", [])
    if not rights_list:
        rights_list = _get_default_rights(doc_type)

    # Get forum info
    forum_info = _get_forum_info(doc_type, state, rights_data, legal_aid_data)

    # Get legal aid eligibility
    eligibility = legal_aid_data.get("nalsa_eligibility", {})
    eligible_categories = eligibility.get("categories", _get_default_nalsa_categories())

    # Build contact info
    contact_info = _get_contact_info(doc_type, state, legal_aid_data)

    legal_aid = LegalAidInfo(
        eligible_categories=eligible_categories,
        forum=forum_info["forum"],
        forum_description=forum_info["description"],
        contact_info=contact_info,
        online_portal=forum_info.get("portal"),
        filing_process=forum_info.get("process", ""),
    )

    return RightsResponse(
        document_type=doc_type,
        state=state,
        rights=rights_list,
        legal_aid=legal_aid,
    )


