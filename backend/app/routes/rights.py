def _get_contact_info(
    doc_type: DocumentType,
    state: str,
    legal_aid_data: dict,
) -> dict[str, str]:
    """Get contact information for the relevant authority."""
    # Try to find state-specific DLSA contact
    dlsa_contacts = legal_aid_data.get("dlsa_contacts", {})
    state_lower = state.lower().strip()

    state_contact = dlsa_contacts.get(state_lower, {})

    contacts: dict[str, str] = {}

    if state_contact:
        contacts.update(state_contact)
    else:
        # Default NALSA contact
        contacts = {
            "authority": "National Legal Services Authority (NALSA)",
            "address": "12/11, Jam Nagar House, Shahjahan Road, New Delhi - 110011",
            "phone": "011-23382778",
            "website": "https://nalsa.gov.in",
            "note": f"TODO: verify DLSA contact for {state}. Please search for your District Legal Services Authority.",
        }

    # Add type-specific portals
    if doc_type == DocumentType.CONSUMER:
        contacts["e_daakhil_portal"] = "https://edaakhil.nic.in"
        contacts["consumer_helpline"] = "1800-11-4000 (National Consumer Helpline)"

    return contacts


